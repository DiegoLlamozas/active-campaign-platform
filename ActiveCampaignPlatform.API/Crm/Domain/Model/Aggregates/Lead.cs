using ActiveCampaignPlatform.API.Crm.Domain.Model.Commands;
using ActiveCampaignPlatform.API.Crm.Domain.Model.ValueObjects;
using ActiveCampaignPlatform.API.Shared.Domain.Model.Aggregates.Internal;

namespace ActiveCampaignPlatform.API.Crm.Domain.Model.Aggregates;

/// <summary>
///     Lead aggregate root of the CRM bounded context.
/// </summary>
/// <remarks>
///     Enforces the lead business rules at creation time: valid names, valid status,
///     default status and the data required by each status.
///     Author: Your Full Name
/// </remarks>
public partial class Lead : AggregateRoot
{
    /// <summary>
    ///     Parameterless constructor required by Entity Framework Core.
    /// </summary>
    private Lead()
    {
        FirstName = null!;
        LastName = null!;
    }

    /// <summary>
    ///     Creates a new lead from a <see cref="CreateLeadCommand" />.
    /// </summary>
    /// <param name="command">The command with the lead data.</param>
    /// <exception cref="ArgumentException">A business rule is broken.</exception>
    public Lead(CreateLeadCommand command)
    {
        ActiveCampaignLeadId = Guid.NewGuid();
        FirstName = new FirstName(command.FirstName);
        LastName = new LastName(command.LastName);
        Status = ParseStatus(command.Status);
        AssignedSalesAgentId = command.AssignedSalesAgentId;
        ContactedAt = command.ContactedAt;
        ApprovedAt = command.ApprovedAt;
        ReportedAt = command.ReportedAt;
        EnsureStatusRequirements();
    }

    /// <summary>Gets the internal identifier (autogenerated primary key, never exposed).</summary>
    public int Id { get; }

    /// <summary>Gets the public, unique identifier generated at registration.</summary>
    public Guid ActiveCampaignLeadId { get; private set; }

    /// <summary>Gets the first name of the lead.</summary>
    public FirstName FirstName { get; private set; }

    /// <summary>Gets the last name of the lead.</summary>
    public LastName LastName { get; private set; }

    /// <summary>Gets the current status of the lead.</summary>
    public ELeadStatus Status { get; private set; }

    /// <summary>Gets the identifier of the assigned sales agent, if any.</summary>
    public int? AssignedSalesAgentId { get; private set; }

    /// <summary>Gets the date the lead was contacted, if any.</summary>
    public DateTime? ContactedAt { get; private set; }

    /// <summary>Gets the date the lead was approved, if any.</summary>
    public DateTime? ApprovedAt { get; private set; }

    /// <summary>Gets the date the lead was reported, if any.</summary>
    public DateTime? ReportedAt { get; private set; }

    /// <summary>
    ///     Converts the raw status value to <see cref="ELeadStatus" />, defaulting to Open.
    /// </summary>
    /// <param name="status">The raw status value, or null.</param>
    /// <returns>The lead status.</returns>
    private static ELeadStatus ParseStatus(int? status)
    {
        var value = status ?? (int)ELeadStatus.Open;
        if (!Enum.IsDefined((ELeadStatus)value))
            throw new ArgumentException($"Status {value} is not a valid lead status.");
        return (ELeadStatus)value;
    }

    /// <summary>
    ///     Verifies that the data required by the current status is present.
    /// </summary>
    private void EnsureStatusRequirements()
    {
        if (Status.RequiresContact() && (AssignedSalesAgentId is null or <= 0 || ContactedAt is null))
            throw new ArgumentException(
                $"A lead with status {Status} requires an assigned sales agent and a contacted date.");

        if (Status.RequiresApproval() && ApprovedAt is null)
            throw new ArgumentException($"A lead with status {Status} requires an approved date.");

        if (Status.RequiresReport() && ReportedAt is null)
            throw new ArgumentException($"A lead with status {Status} requires a reported date.");
    }
}